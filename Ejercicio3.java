public class Ejercicio3 {
    public static void main(String[] args) {
        // Variable contador inicializada en 1
        int contador = 1;

        // El ciclo se repite mientras la condición sea verdadera (hasta 100)
        while (contador <= 100) {
            System.out.println(contador);
            contador++; // Incrementa el contador de 1 en 1
        }
    }
}
